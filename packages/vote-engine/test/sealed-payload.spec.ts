/**
 * sealed-payload.spec.ts — Phase 52 Plan 01 (D-04, D-05)
 *
 * Proves the two cryptographic primitives every other plan in this phase
 * builds on:
 *
 *   D-04 — the domain-separated key split. `lookupId` (the half the
 *          rendezvous service sees) and `contentKey` (the half it must
 *          never see) are two different HMAC-SHA256 derivations of one
 *          20-byte secret. The split is FORCED, not preferred: `redeem()`
 *          is called with the secret itself, so keying the cipher on the
 *          raw secret would hand the service the decryption key alongside
 *          the ciphertext.
 *
 *   D-05 — the AES-256-GCM seal/unseal wrapper over the
 *          `{ v, nonce, ciphertext }` base64url shape.
 *
 * Two DIFFERENT kinds of vector live in this file and must not be
 * conflated:
 *
 *   a) INDEPENDENT-IMPLEMENTATION KATs (KAT-1/2/3). Computed here from
 *      `node:crypto` (OpenSSL) and compared against `@noble/*`. These are
 *      genuine cross-implementation checks — a bug shared by both
 *      implementations is the only way they pass wrongly. `node:crypto` is
 *      a TEST-TIER tool only; importing it from `src/bootstrap/` is
 *      forbidden and G-3 enforces that.
 *
 *   b) FROZEN REGRESSION PINS (`FROZEN_*`). Generated by this repo, not by
 *      an independent authority. They prove nothing about correctness; they
 *      exist so a later refactor that swaps the HMAC argument order,
 *      renames a label, or changes the encoding fails loudly. They are also
 *      the cross-runtime parity vectors 52-05 (browser) and 52-07 (Hermes)
 *      re-run byte-for-byte.
 *
 * DECLARED BLIND SPOT: this spec proves the primitives' ARITHMETIC on the
 * host running mocha. It says nothing about whether Metro/Hermes can bundle
 * `@noble/ciphers` at all, nor whether `crypto.getRandomValues` is present
 * on a real device — that proof is 52-07's device gate. It also exercises
 * no transport, no service and no IndexedDB.
 */

