const toBase64url = (bytes: Uint8Array): string => Buffer.from(bytes).toString('base64url')
const fromBase64url = (s: string): Uint8Array => new Uint8Array(Buffer.from(s, 'base64url'))

/** Independent (OpenSSL) reference for one label. Label is HMAC's KEY slot. */
function nodeHmac (label: string, secret: Uint8Array): Buffer {
  return createHmac('sha256', Buffer.from(label, 'utf8')).update(secret).digest()
}

/** Independent (OpenSSL) reference for the whole cipher step, tag appended. */
function nodeSeal (contentKey: Uint8Array, nonce: Uint8Array, lookupId: string, plaintext: string): Buffer {
  const cipher = createCipheriv('aes-256-gcm', contentKey, nonce)
  cipher.setAAD(Buffer.from(lookupId, 'utf8'))
  const body = Buffer.concat([cipher.update(Buffer.from(plaintext, 'utf8')), cipher.final()])
  return Buffer.concat([body, cipher.getAuthTag()])
}

