// ---------------------------------------------------------------------------
// Task 3 — the four negative controls and the D-04 no-leak structural guards
//
// Negative controls are the POINT of this plan, not an afterthought: a round
// trip that only tests the happy path proves almost nothing. Every rejection
// case below asserts its REASON (not merely `ok === false`), and the block
// carries a paired positive control at the end so it cannot pass vacuously
// against an implementation that refuses everything.
// ---------------------------------------------------------------------------

/** The two splits every negative control below is built from. */
const splitA = deriveBootstrapKeys(FROZEN_SECRET)
const splitB = deriveBootstrapKeys(OTHER_SECRET)

/** A valid wrapper over the canary plaintext, sealed under splitA. */
function makeValidWrapper (plaintext: string = CANARY_PLAINTEXT): SealedPayload {
  return sealPayload(plaintext, splitA)
}

/** Rebuild a wrapper with one member replaced. Keeps member order v/nonce/ciphertext. */
function withMember (wrapper: SealedPayload, patch: Record<string, unknown>): Record<string, unknown> {
  return { v: wrapper.v, nonce: wrapper.nonce, ciphertext: wrapper.ciphertext, ...patch }
}

/** Flip the low bit of one byte, re-encode. */
function flipBitAt (b64u: string, index: number): string {
  const bytes = fromBase64url(b64u)
  bytes[index] = bytes[index]! ^ 0x01
  return toBase64url(bytes)
}

const CONTENT_KEY_HEX = Buffer.from(splitA.contentKey).toString('hex')
const CONTENT_KEY_BASE64 = Buffer.from(splitA.contentKey).toString('base64')
const CONTENT_KEY_BASE64URL = Buffer.from(splitA.contentKey).toString('base64url')

describe('bootstrap sealed payload — negative controls and no-leak guards (52-01)', () => {
  // -------------------------------------------------------------------------
  // NC-1 — wrong key (the KEY is the only variable; the AAD is correct)
  // -------------------------------------------------------------------------
  describe('NC-1 — wrong contentKey', () => {
    it('NC-1a: refuses with authentication-failed when only the contentKey differs', () => {
      const wrapper = makeValidWrapper()
      const wrongKeyOnly: BootstrapKeySplit = { lookupId: splitA.lookupId, contentKey: splitB.contentKey }
      const result = unsealPayload(wrapper, wrongKeyOnly)
      expect(result.ok, 'a wrong key must not unseal').to.equal(false)
      if (!result.ok) {
        expect(result.reason, 'a wrong key is an AEAD failure').to.equal('authentication-failed')
      }
    })

    it('NC-1b: the refusal object carries no plaintext member at all', () => {
      const wrongKeyOnly: BootstrapKeySplit = { lookupId: splitA.lookupId, contentKey: splitB.contentKey }
      const result = unsealPayload(makeValidWrapper(), wrongKeyOnly)
      expect('plaintext' in result, 'a refusal must not carry a partial artifact').to.equal(false)
      expect(JSON.stringify(result), 'the refusal must not leak the plaintext canary').to.not.contain(PII_CANARY)
    })
  })

  // -------------------------------------------------------------------------
  // NC-2 — tampered ciphertext (body, tag, truncation)
  // -------------------------------------------------------------------------
  describe('NC-2 — tampered ciphertext', () => {
    it('NC-2a: a single flipped bit in the MESSAGE BODY refuses with authentication-failed', () => {
      const wrapper = makeValidWrapper()
      const tampered = withMember(wrapper, { ciphertext: flipBitAt(wrapper.ciphertext, 0) })
      const result = unsealPayload(tampered, splitA)
      expect(result.ok, 'a body bit-flip must not unseal').to.equal(false)
      if (!result.ok) expect(result.reason, 'a body bit-flip is an AEAD failure').to.equal('authentication-failed')
      expect('plaintext' in result, 'no plaintext on refusal').to.equal(false)
    })

    it('NC-2b: a single flipped bit INSIDE THE 16-BYTE TAG refuses too (the tag is checked, not merely carried)', () => {
      const wrapper = makeValidWrapper()
      const length = fromBase64url(wrapper.ciphertext).length
      const tagByte = length - 8 // strictly inside the trailing 16-byte tag
      expect(tagByte, 'the chosen index must lie inside the tag').to.be.greaterThanOrEqual(length - 16)
      const tampered = withMember(wrapper, { ciphertext: flipBitAt(wrapper.ciphertext, tagByte) })
      const result = unsealPayload(tampered, splitA)
      expect(result.ok, 'a tag bit-flip must not unseal').to.equal(false)
      if (!result.ok) expect(result.reason, 'a tag bit-flip is an AEAD failure').to.equal('authentication-failed')
    })

    it('NC-2c: a ciphertext shorter than the 16-byte tag is refused, not crashed on', () => {
      const wrapper = makeValidWrapper()
      const truncated = withMember(wrapper, { ciphertext: toBase64url(fromBase64url(wrapper.ciphertext).slice(0, 8)) })
      let result: ReturnType<typeof unsealPayload> | undefined
      expect(() => { result = unsealPayload(truncated, splitA) }, 'unsealPayload must never throw').to.not.throw()
      expect(result?.ok, 'a below-tag-length ciphertext must not unseal').to.equal(false)
      if (result !== undefined && !result.ok) {
        // Deliberately the SAME reason as a wrong key: ciphertext length must
        // not be a separately distinguishable oracle (T-52-01-06).
        expect(result.reason, 'truncation shares the single AEAD reason on purpose').to.equal('authentication-failed')
      }
    })

    it('NC-2d: a flipped bit in the NONCE refuses with authentication-failed (nonce is still 12 bytes)', () => {
      const wrapper = makeValidWrapper()
      const tampered = withMember(wrapper, { nonce: flipBitAt(wrapper.nonce, 3) })
      const result = unsealPayload(tampered, splitA)
      expect(result.ok, 'a nonce bit-flip must not unseal').to.equal(false)
      if (!result.ok) expect(result.reason).to.equal('authentication-failed')
    })
  })

  // -------------------------------------------------------------------------
  // NC-3 — wrong AAD (the lookupId is the only variable; the key is correct)
  // -------------------------------------------------------------------------
  describe('NC-3 — wrong AAD (lookupId)', () => {
    it('NC-3a: refuses with authentication-failed when only the lookupId/AAD differs', () => {
      const wrapper = makeValidWrapper()
      const wrongAadOnly: BootstrapKeySplit = { lookupId: splitB.lookupId, contentKey: splitA.contentKey }
      const result = unsealPayload(wrapper, wrongAadOnly)
      expect(result.ok, 'a wrong AAD must not unseal even with the correct key').to.equal(false)
      if (!result.ok) expect(result.reason).to.equal('authentication-failed')
    })

    it('NC-3b: nothing in the refusal carries the original plaintext (this is the failure D-04 AAD binding prevents)', () => {
      const wrongAadOnly: BootstrapKeySplit = { lookupId: splitB.lookupId, contentKey: splitA.contentKey }
      const result = unsealPayload(makeValidWrapper(), wrongAadOnly)
      expect('plaintext' in result, 'delivering a payload under the wrong record identity is the exact failure mode').to.equal(false)
      expect(JSON.stringify(result), 'the refusal must not leak the plaintext canary').to.not.contain(PII_CANARY)
      expect(JSON.stringify(result), 'the refusal must not leak any plaintext fragment').to.not.contain('registrant')
    })

    it('NC-3c: the correct AAD with the correct key still unseals (paired positive control)', () => {
      const result = unsealPayload(makeValidWrapper(), splitA)
      expect(result.ok, 'NC-3 must isolate the AAD, not refuse everything').to.equal(true)
    })
  })

  // -------------------------------------------------------------------------
  // NC-4 — version gate, proven to run BEFORE decryption
  // -------------------------------------------------------------------------
  describe('NC-4 — unknown or malformed version', () => {
    it('NC-4a: v = 2 with a fully correct split reports unsupported-version, NOT authentication-failed', () => {
      const wrapper = makeValidWrapper()
      const result = unsealPayload(withMember(wrapper, { v: 2 }), splitA)
      expect(result.ok, 'an unknown version must be refused').to.equal(false)
      if (!result.ok) {
        expect(result.reason, 'the version gate must run BEFORE decryption').to.equal('unsupported-version')
        // The load-bearing half of this test: with a CORRECT key, an
        // implementation that decrypted first would have succeeded or reported
        // an AEAD failure. Either would prove the ordering wrong.
        expect(result.reason, 'reporting an AEAD failure here would prove decryption ran first').to.not.equal('authentication-failed')
        expect(result.detail, 'the detail names the observed version').to.contain('2')
      }
    })

    it('NC-4b: v = 0 reports unsupported-version', () => {
      const result = unsealPayload(withMember(makeValidWrapper(), { v: 0 }), splitA)
      expect(result.ok).to.equal(false)
      if (!result.ok) expect(result.reason, 'v is a number, just not the locked one').to.equal('unsupported-version')
    })

    it("NC-4c: v = '1' (a string, not a number) reports malformed-wrapper", () => {
      const result = unsealPayload(withMember(makeValidWrapper(), { v: '1' }), splitA)
      expect(result.ok).to.equal(false)
      if (!result.ok) {
        expect(result.reason, 'a wrong-typed v is structural, not a version question').to.equal('malformed-wrapper')
        expect(result.detail, "the detail names the offending member 'v'").to.contain("'v'")
      }
    })

    it('NC-4d: a missing v reports malformed-wrapper naming the member', () => {
      const wrapper = makeValidWrapper()
      const result = unsealPayload({ nonce: wrapper.nonce, ciphertext: wrapper.ciphertext }, splitA)
      expect(result.ok).to.equal(false)
      if (!result.ok) {
        expect(result.reason).to.equal('malformed-wrapper')
        expect(result.detail, "the detail names the missing member 'v'").to.contain("'v'")
      }
    })

    it('NC-4e: v = 1 with the same split unseals (paired positive control for the version gate)', () => {
      const wrapper = makeValidWrapper()
      const result = unsealPayload(withMember(wrapper, { v: SEALED_PAYLOAD_FORMAT_VERSION }), splitA)
      expect(result.ok, 'the version gate must accept the locked version').to.equal(true)
    })
  })

  // -------------------------------------------------------------------------
  // NC-5 — malformed wrappers, with the detail-leak canary scan
  // -------------------------------------------------------------------------
  describe('NC-5 — malformed wrapper', () => {
    const validNonce = 'oKGio6Slpqeoqaqr' // 12 bytes, base64url
    const collectedDetails: string[] = []

    /** Every case: input, the member (or structural fault) its detail must name. */
    function cases (): ReadonlyArray<readonly [string, unknown, string]> {
      const wrapper = makeValidWrapper()
      return [
        ['null', null, 'null'],
        ['a plain string', 'not-a-wrapper', 'object'],
        ['an array', [1, 2, 3], 'array'],
        ['an empty object', {}, "'v'"],
        ['a wrapper missing nonce', { v: 1, ciphertext: wrapper.ciphertext }, "'nonce'"],
        ['a wrapper missing ciphertext', { v: 1, nonce: wrapper.nonce }, "'ciphertext'"],
        ['a nonce decoding to 11 bytes', withMember(wrapper, { nonce: toBase64url(new Uint8Array(11)) }), "'nonce'"],
        ['a nonce decoding to 13 bytes', withMember(wrapper, { nonce: toBase64url(new Uint8Array(13)) }), "'nonce'"],
        ["a nonce containing '+' (standard base64, not base64url)", withMember(wrapper, { nonce: validNonce.slice(0, 14) + '+r' }), "'nonce'"],
        ["a nonce containing '/' (standard base64, not base64url)", withMember(wrapper, { nonce: validNonce.slice(0, 14) + '/r' }), "'nonce'"],
        ["a ciphertext containing '=' padding", withMember(wrapper, { ciphertext: wrapper.ciphertext + '=' }), "'ciphertext'"],
        ['a nonce that is a number, not a string', withMember(wrapper, { nonce: 12 }), "'nonce'"],
        ['a ciphertext that is null, not a string', withMember(wrapper, { ciphertext: null }), "'ciphertext'"]
      ]
    }

    for (const [label, input, mustName] of cases()) {
      it(`NC-5: ${label} refuses with malformed-wrapper, detail naming ${mustName}`, () => {
        let result: ReturnType<typeof unsealPayload> | undefined
        expect(() => { result = unsealPayload(input, splitA) }, 'unsealPayload must never throw').to.not.throw()
        expect(result?.ok, `${label} must be refused`).to.equal(false)
        if (result !== undefined && !result.ok) {
          expect(result.reason, `${label} is a structural fault`).to.equal('malformed-wrapper')
          expect(result.detail, `${label}: detail must name the structural fault`).to.contain(mustName)
          collectedDetails.push(result.detail)
        }
      })
    }

    it('NC-5z: no detail string from any case above contains plaintext, key or ciphertext material', () => {
      expect(collectedDetails.length, 'the scan must have something to scan').to.be.greaterThan(10)
      const wrapper = makeValidWrapper()
      for (const detail of collectedDetails) {
        expect(detail, 'a detail must never carry the plaintext canary').to.not.contain(PII_CANARY)
        expect(detail.toLowerCase(), 'a detail must never carry the contentKey as hex').to.not.contain(CONTENT_KEY_HEX.toLowerCase())
        expect(detail, 'a detail must never carry the contentKey as base64').to.not.contain(CONTENT_KEY_BASE64)
        expect(detail, 'a detail must never carry the contentKey as base64url').to.not.contain(CONTENT_KEY_BASE64URL)
        expect(detail, 'a detail must never quote the ciphertext back').to.not.contain(wrapper.ciphertext.slice(0, 16))
        expect(detail, 'a detail must never carry the lookupId').to.not.contain(splitA.lookupId)
      }
    })

    it('NC-5+: POSITIVE CONTROL — the unmodified wrapper with the correct split still unseals exactly', () => {
      const wrapper = sealPayload(CANARY_PLAINTEXT, splitA)
      const result = unsealPayload(wrapper, splitA)
      expect(result.ok, 'without this the whole negative block could pass vacuously').to.equal(true)
      if (result.ok) expect(result.plaintext).to.equal(CANARY_PLAINTEXT)
    })
  })

  // -------------------------------------------------------------------------
  // G-1 — the contentKey never crosses the wire (D-04's structural guarantee)
  // -------------------------------------------------------------------------
  describe('G-1 — contentKey has no wire form (T-52-01-01)', () => {
    it('G-1a: the wrapper has EXACTLY the members ciphertext, nonce, v (set equality, so a new field fails loudly)', () => {
      const wrapper = sealPayload(CANARY_PLAINTEXT, splitA)
      expect(Object.keys(wrapper).sort(), 'widening the wire silently is the failure this catches').to.deep.equal(['ciphertext', 'nonce', 'v'])
    })

    it('G-1b: JSON.stringify of the wrapper contains the contentKey in NONE of base64url, base64 or hex', () => {
      const serialized = JSON.stringify(sealPayload(CANARY_PLAINTEXT, splitA))
      expect(serialized, 'contentKey must not appear as base64url').to.not.contain(CONTENT_KEY_BASE64URL)
      expect(serialized, 'contentKey must not appear as standard base64').to.not.contain(CONTENT_KEY_BASE64)
      expect(serialized.toLowerCase(), 'contentKey must not appear as lowercase hex').to.not.contain(CONTENT_KEY_HEX.toLowerCase())
      expect(serialized.toUpperCase(), 'contentKey must not appear as uppercase hex').to.not.contain(CONTENT_KEY_HEX.toUpperCase())
    })

    it('G-1c: the lookupId — the half that DOES go to the service — carries none of the contentKey either', () => {
      const serialized = JSON.stringify(deriveBootstrapKeys(FROZEN_SECRET).lookupId)
      expect(serialized, 'lookupId must not embed the contentKey as base64url').to.not.contain(CONTENT_KEY_BASE64URL)
      expect(serialized, 'lookupId must not embed the contentKey as standard base64').to.not.contain(CONTENT_KEY_BASE64)
      expect(serialized.toLowerCase(), 'lookupId must not embed the contentKey as hex').to.not.contain(CONTENT_KEY_HEX.toLowerCase())
    })

    it('G-1d: the contentKey is raw bytes with no string form on the split object', () => {
      const split = deriveBootstrapKeys(FROZEN_SECRET)
      expect(Object.keys(split).sort(), 'the split has exactly two members').to.deep.equal(['contentKey', 'lookupId'])
      expect(split.contentKey, 'contentKey is Uint8Array-only').to.be.instanceOf(Uint8Array)
      expect(typeof split.lookupId, 'lookupId is the only string member').to.equal('string')
    })
  })

  // -------------------------------------------------------------------------
  // G-2 / G-3 — structural source guards
  // -------------------------------------------------------------------------
  describe('G-2/G-3 — source-level structural guards', () => {
    const SRC_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'bootstrap')
    const readSrc = (name: string): string => readFileSync(join(SRC_DIR, name), 'utf8')

    /** Same best-effort stripper as `browser-entry-purity.spec.ts:127-131`. MANDATORY: this module's header names Node builtins deliberately, in prose. */
    function stripComments (src: string): string {
      return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')
    }

    it('G-2: the ./bootstrap barrel does not expose the nonce-injecting entry point (but does expose sealPayload)', () => {
      const barrel = readSrc('index.ts')
      // Constructed at runtime so this assertion does not itself put the
      // forbidden symbol name into index.ts's grep-visible neighbours.
      const forbidden = 'sealPayload' + 'WithNonce'
      expect(barrel.includes(forbidden), 'a pinned production nonce must be unreachable through the barrel').to.equal(false)
      expect(barrel, 'paired positive control: the safe entry point IS exported').to.contain('sealPayload')
      expect(barrel, 'the barrel must re-export the key split').to.contain('deriveBootstrapKeys')
      expect(barrel, 'the barrel must re-export the unseal path').to.contain('unsealPayload')
      expect(barrel, 'the re-export must point at this module').to.match(/from '\.\/sealed-payload\.js'/)
    })

    it('G-3a: comment-stripped sealed-payload.ts contains no Node builtin, no byte-buffer type and no CommonJS call', () => {
      const stripped = stripComments(readSrc('sealed-payload.ts'))
      expect(stripped, "no 'node:' specifier").to.not.match(/node:/)
      expect(stripped, "no bare 'crypto'/'fs'/'path'/'buffer' import").to.not.match(/from\s+['"](crypto|fs|path|buffer)['"]/)
      expect(stripped, 'no CommonJS require call').to.not.match(/require\s*\(/)
      expect(stripped, 'no Buffer identifier').to.not.match(/\bBuffer\b/)
      expect(stripped, "no import of '../utils.js' (it drags the Quereus layer into a browser bundle)").to.not.match(/from\s+['"]\.\.\/utils\.js['"]/)
      // Paired positive control: the stripper did not simply erase everything.
      expect(stripped, 'the stripper must leave the real code behind').to.contain('deriveBootstrapKeys')
    })

    it('G-3b: the bare specifiers sealed-payload.ts imports are EXACTLY the pinned five (two-directional set equality)', () => {
      const stripped = stripComments(readSrc('sealed-payload.ts'))
      const found = new Set<string>()
      for (const match of stripped.matchAll(/from\s+['"]([^'"]+)['"]/g)) {
        const specifier = match[1]!
        if (!specifier.startsWith('.')) found.add(specifier)
      }
      const expected = [
        '@noble/ciphers/aes.js',
        '@noble/ciphers/utils.js',
        '@noble/hashes/hmac.js',
        '@noble/hashes/sha2.js',
        '@noble/hashes/utils.js'
      ]
      expect([...found].sort(), 'a later edit reaching for a Node builtin must fail HERE, not at a device cold start').to.deep.equal(expected)
    })
  })
})
