describe('associate() — election-terms attestation policy gate (D-14c, Assumption A5)', () => {
  describe('AttestationRequired=0: verify() is SKIPPED', () => {
    it('associate() SUCCEEDS with a throw-if-called verifier and writes exactly one Association row', async () => {
      const { auth, registrantId, registrationEngine, sign, electionId } = await setupAssociationTest()
      await registrationEngine.setElectionAttestationPolicy(electionId, false, sign)

      const engine = new AssociationEngine(auth.ctx, throwIfCalledVerifier)
      const deviceKey = nextDeviceKey()
      const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
      const attestation = makeDeviceAttestation()

      // Resolving (not throwing) is itself the proof — the sentinel verifier would have
      // thrown if associate() had called verify() at all.
      await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)

      const row = await auth.ctx.db
        .prepare('select count(*) as n from Association where RegistrantId = :registrantId and DeviceKey = :deviceKey')
        .get({ registrantId, deviceKey })
      expect(Number(row?.n)).to.equal(1)
    })
  })

  describe('AttestationRequired=1: verify() is CALLED (real PlayIntegrityVerifier)', () => {
    it('positive: a default (accepted) synthetic DeviceAttestation makes associate() succeed', async () => {
      const { auth, registrantId, registrationEngine, sign, electionId } = await setupAssociationTest()
      await registrationEngine.setElectionAttestationPolicy(electionId, true, sign)
      const { verifier, jweKeys, testRoot } = await buildRealVerifier()

      const engine = new AssociationEngine(auth.ctx, verifier)
      const deviceKey = nextDeviceKey()
      const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
      const attestation = await buildSyntheticDeviceAttestation({ challenge, jweKeys, testRoot })

      await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)

      const row = await auth.ctx.db
        .prepare('select count(*) as n from Association where RegistrantId = :registrantId and DeviceKey = :deviceKey')
        .get({ registrantId, deviceKey })
      expect(Number(row?.n)).to.equal(1)
    })

    it('negative (wrong-nonce, D-06 relay attempt): associate() THROWS', async () => {
      const { auth, registrantId, registrationEngine, sign, electionId } = await setupAssociationTest()
      await registrationEngine.setElectionAttestationPolicy(electionId, true, sign)
      const { verifier, jweKeys, testRoot } = await buildRealVerifier()

      const engine = new AssociationEngine(auth.ctx, verifier)
      const deviceKey = nextDeviceKey()
      const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
      const attestation = await buildSyntheticDeviceAttestation({
        challenge,
        jweKeys,
        testRoot,
        overrides: { payloadNonce: 'this-is-not-the-bound-digest' }
      })

      let threw = false
      try {
        await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)
      } catch {
        threw = true
      }
      expect(threw, 'expected a wrong-nonce attestation to be rejected').to.be.true
    })

    it('negative (tampered JWE ciphertext): associate() THROWS', async () => {
      const { auth, registrantId, registrationEngine, sign, electionId } = await setupAssociationTest()
      await registrationEngine.setElectionAttestationPolicy(electionId, true, sign)
      const { verifier, jweKeys, testRoot } = await buildRealVerifier()

      const engine = new AssociationEngine(auth.ctx, verifier)
      const deviceKey = nextDeviceKey()
      const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
      const attestation = await buildSyntheticDeviceAttestation({
        challenge,
        jweKeys,
        testRoot,
        overrides: { jwe: { tamperCiphertext: true } }
      })

      let threw = false
      try {
        await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)
      } catch {
        threw = true
      }
      expect(threw, 'expected a tampered-ciphertext attestation to be rejected').to.be.true
    })

    it('negative (Software-only key attestation, D-02 balanced bar): associate() THROWS', async () => {
      const { auth, registrantId, registrationEngine, sign, electionId } = await setupAssociationTest()
      await registrationEngine.setElectionAttestationPolicy(electionId, true, sign)
      const { verifier, jweKeys, testRoot } = await buildRealVerifier()

      const engine = new AssociationEngine(auth.ctx, verifier)
      const deviceKey = nextDeviceKey()
      const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
      const attestation = await buildSyntheticDeviceAttestation({
        challenge,
        jweKeys,
        testRoot,
        overrides: { securityLevel: SecurityLevel.software }
      })

      let threw = false
      try {
        await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)
      } catch {
        threw = true
      }
      expect(threw, 'expected a Software-only key attestation to be rejected').to.be.true
    })
  })

  describe('no ElectionAttestationPolicy row (unconfigured election): fail-closed (Assumption A5)', () => {
    it('associate() THROWS via the throw-if-called sentinel — absence of a policy row defaults to attestation REQUIRED', async () => {
      const { auth, registrantId, sign, electionId } = await setupAssociationTest()
      // Deliberately no setElectionAttestationPolicy call for electionId — no row exists.

      const engine = new AssociationEngine(auth.ctx, throwIfCalledVerifier)
      const deviceKey = nextDeviceKey()
      const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
      const attestation = makeDeviceAttestation()

      let threw = false
      try {
        await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)
      } catch {
        threw = true
      }
      // The throw comes from throwIfCalledVerifier.verify() — proving verify() WAS invoked
      // even though no ElectionAttestationPolicy row exists for this electionId (A5/CR-03).
      expect(threw, 'expected associate() to throw (via the sentinel) when no policy row exists').to.be.true
    })
  })
})

