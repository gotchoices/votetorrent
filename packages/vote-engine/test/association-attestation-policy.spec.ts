/** Build a real secp256k1 sign callback (@noble/curves v2 defaults — prehash:true). */
function makeRealSigner (userId: string): { sign: (digest: Uint8Array) => Promise<Signature> } {
  const { privateHex, publicHex } = randomTestKeyPair()
  const privBytes = hexToBytes(privateHex)
  const sign = async (digest: Uint8Array): Promise<Signature> => {
    const sig = secp256k1.sign(digest, privBytes) // v2 default: prehash:true
    return { signerUserId: userId, signerKey: publicHex, signature: bytesToHex(sig) }
  }
  return { sign }
}

let registrantSeq = 0
function nextRegistrantId (): string {
  registrantSeq += 1
  return `assoc-policy-registrant-${Date.now()}-${registrantSeq}`
}

let deviceSeq = 0
function nextDeviceKey (): string {
  deviceSeq += 1
  return `assoc-policy-device-key-${Date.now()}-${deviceSeq}`
}

const FUTURE_REGISTRANT_EXPIRATION = Date.now() + 365 * 86_400_000
const FUTURE_CHALLENGE_EXPIRATION = new Date(Date.now() + 10 * 60_000).toISOString()

function makeDeviceAttestation (overrides?: Partial<DeviceAttestation>): DeviceAttestation {
  deviceSeq += 1
  return {
    publicKey: `assoc-policy-device-pubkey-${deviceSeq}`,
    deviceId: `assoc-policy-device-id-${Date.now()}-${deviceSeq}`,
    attestationTime: Date.now(),
    certificateChain: ['cert-a', 'cert-b'],
    ...overrides
  }
}

/** Resolve the single Election row seeded by addTestElection() for this authority (mirrors association.spec.ts). */
async function resolveElectionId (ctx: EngineContext, authorityId: string): Promise<string> {
  const row = await ctx.db
    .prepare('select Id from Election where AuthorityId = :authorityId limit 1')
    .get({ authorityId })
  if (!row) throw new Error('resolveElectionId: Election not found for authority')
  return row.Id as string
}

/** Seed an active Registrant (Status='a') AND an Election, returning both plus the resolved electionId. */
async function setupAssociationTest (): Promise<{
  auth: TestAuthorityContext
  registrantId: string
  registrationEngine: RegistrationEngine
  sign: (digest: Uint8Array) => Promise<Signature>
  electionId: string
}> {
  const net = await createTestNetwork()
  const auth = await addTestAuthority(net)
  const { sign } = makeRealSigner(auth.user.id)
  const registrationEngine = new RegistrationEngine(auth.ctx)
  const registrantId = nextRegistrantId()
  await registrationEngine.createRegistrant(
    { id: registrantId, authorityId: auth.authority.id, privateCid: 'assoc-policy-test-private-cid-placeholder', expiration: FUTURE_REGISTRANT_EXPIRATION },
    sign
  )
  const elec = await addTestElection(auth)
  const electionId = await resolveElectionId(elec.ctx, elec.authority.id)
  return { auth, registrantId, registrationEngine, sign, electionId }
}

/** A verifier that ALWAYS throws — proves whether verify() was ever invoked at all. */
const throwIfCalledVerifier: IAttestationVerifier = {
  async verify (): Promise<AttestationVerification> {
    throw new Error('verify() must not run on the non-attested (AttestationRequired=0) path — D-14c')
  }
}

/** Build the REAL PlayIntegrityVerifier exactly as authority-transport.spec.ts does. */
async function buildRealVerifier (): Promise<{ verifier: PlayIntegrityVerifier, jweKeys: Awaited<ReturnType<typeof generateSyntheticJweKeyMaterial>>, testRoot: Awaited<ReturnType<typeof generateTestRootCa>> }> {
  const jweKeys = await generateSyntheticJweKeyMaterial()
  const testRoot = await generateTestRootCa()
  const keyProvider: IIntegrityKeyProvider = {
    getDecryptionKey: async () => jweKeys.decryptionKey,
    getVerificationKey: async () => jweKeys.verificationPublicKey
  }
  const verifier = new PlayIntegrityVerifier(keyProvider, [new Uint8Array(testRoot.cert.rawData)], SYNTHETIC_EXPECTED_APP_IDENTITY)
  return { verifier, jweKeys, testRoot }
}

