describe('associate() — D-14e minimal AssociationPrivate + device-uniqueness (non-attested path)', () => {
  it('AttestationRequired=0 success writes exactly one minimal AssociationPrivate row for (registrantId, deviceKey)', async () => {
    const { auth, registrantId, registrationEngine, sign, electionId } = await setupAssociationTest()
    await registrationEngine.setElectionAttestationPolicy(electionId, false, sign)

    const engine = new AssociationEngine(auth.ctx, throwIfCalledVerifier)
    const deviceKey = nextDeviceKey()
    const challenge = await engine.issueAttestationChallenge(registrantId, deviceKey, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
    // Non-attested attestation shape: deviceId populated, no cert-chain/platform material —
    // still all that's needed for the D-06 device-uniqueness check (keyed on DeviceId).
    const attestation = makeDeviceAttestation({ certificateChain: [], platformDetails: undefined })

    await engine.associate({ registrantId, deviceKey, nonce: challenge.nonce, attestation }, sign)

    const privateRow = await auth.ctx.db
      .prepare('select count(*) as n from AssociationPrivate where RegistrantId = :registrantId and DeviceKey = :deviceKey')
      .get({ registrantId, deviceKey })
    expect(Number(privateRow?.n)).to.equal(1)

    const cidRow = await auth.ctx.db
      .prepare('select AttestationCid from Association where RegistrantId = :registrantId and DeviceKey = :deviceKey')
      .get({ registrantId, deviceKey })
    expect(cidRow?.AttestationCid).to.be.a('string').with.length.greaterThan(0)
  })

  it('a second registrant reusing the SAME DeviceId on the non-attested path is REJECTED (uniqueness is path-independent)', async () => {
    const { auth, registrantId: registrantA, registrationEngine, sign, electionId } = await setupAssociationTest()
    await registrationEngine.setElectionAttestationPolicy(electionId, false, sign)

    const registrantB = nextRegistrantId()
    await registrationEngine.createRegistrant(
      { id: registrantB, authorityId: auth.authority.id, privateCid: 'assoc-policy-test-private-cid-b', expiration: FUTURE_REGISTRANT_EXPIRATION },
      sign
    )

    const engine = new AssociationEngine(auth.ctx, throwIfCalledVerifier)
    const sharedDeviceId = `assoc-policy-shared-device-${Date.now()}`

    const deviceKeyA = nextDeviceKey()
    const challengeA = await engine.issueAttestationChallenge(registrantA, deviceKeyA, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
    await engine.associate(
      { registrantId: registrantA, deviceKey: deviceKeyA, nonce: challengeA.nonce, attestation: makeDeviceAttestation({ deviceId: sharedDeviceId, certificateChain: [], platformDetails: undefined }) },
      sign
    )

    const deviceKeyB = nextDeviceKey()
    const challengeB = await engine.issueAttestationChallenge(registrantB, deviceKeyB, FUTURE_CHALLENGE_EXPIRATION, sign, electionId)
    let threw = false
    try {
      await engine.associate(
        { registrantId: registrantB, deviceKey: deviceKeyB, nonce: challengeB.nonce, attestation: makeDeviceAttestation({ deviceId: sharedDeviceId, certificateChain: [], platformDetails: undefined }) },
        sign
      )
    } catch {
      threw = true
    }
    expect(threw, 'expected the second registrant reusing the same DeviceId (no waiver) to be rejected').to.be.true

    const privateRowB = await auth.ctx.db
      .prepare('select count(*) as n from AssociationPrivate where RegistrantId = :registrantId')
      .get({ registrantId: registrantB })
    expect(Number(privateRowB?.n)).to.equal(0)
  })
})
