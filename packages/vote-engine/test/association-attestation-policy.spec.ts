/**
 * association-attestation-policy.spec.ts — Phase 45-07 mocha/chai regression guard for the
 * election-terms attestation policy branch (D-14c, Assumption A5) and the minimal
 * AssociationPrivate device-uniqueness invariant (D-14e) on the non-attested path.
 *
 * Covers:
 *   - D-14c skip-verify: AttestationRequired=0 -> associate() succeeds even with a verifier
 *     whose verify() THROWS if ever invoked (the throw would be the proof it ran).
 *   - D-14c call-verify: AttestationRequired=1 -> associate() runs the REAL PlayIntegrityVerifier
 *     (Phase 43 synthetic-fixture harness, mirroring authority-transport.spec.ts) — a positive
 *     (accepted) case plus three negatives (wrong-nonce / tampered-jwe / Software security level)
 *     that all make associate() throw.
 *   - Assumption A5 fail-closed: no ElectionAttestationPolicy row for the election ->
 *     associate() still invokes verify() (proved by the throw-if-called sentinel) — absence of
 *     configuration defaults to REQUIRED, never an open hole.
 *   - D-14e: the non-attested (AttestationRequired=0) path still writes a minimal
 *     AssociationPrivate row, and device-uniqueness (DeviceId collision across registrants) holds
 *     identically on that path — a second registrant reusing the same DeviceId is rejected.
 *
 * NOT jest/mocha-coverable — deferred to 45-09's on-device Pixel 8 proof per 45-VALIDATION.md's
 * Manual-Only table (threat T-45-02 mitigation, made explicit here so the false-positive
 * boundary — "jest green" vs "device broken" — is documented at the point a reader would assume
 * this suite proves more than it does):
 *   - Real StrongBox/TEE hardware key generation and biometric-gated per-use signing (all key
 *     material here is Node-synthetic, generated by the Phase 43 fixtures, never a real Keystore).
 *   - `KeyPermanentlyInvalidatedException` on biometric-enrollment change (D-13) — no real
 *     Android Keystore in this runtime to invalidate.
 *   - `ADD COLUMN` re-attach safety for the schema changes this phase's plans introduced.
 *   - The D-16b Digest() module-load probe running on REAL Hermes (this suite runs on Node;
 *     `real-attestation-producer.test.ts` covers the probe's CONTRACT shape under jest/Node only).
 *   - The `EXPECTED_APP_PACKAGE` app-identity check against a REAL Play Integrity token from a
 *     REAL device (this suite's synthetic JWE/JWS tokens are Node-fabricated).
 */

